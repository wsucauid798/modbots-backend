import {
  createHash,
  createPrivateKey,
  createPublicKey,
  generateKeyPairSync,
  sign,
} from "node:crypto";
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const [
  manifestArgument,
  privateKeyArgument,
  publicModuleArgument,
  publicRecordArgument,
] =
  process.argv.slice(2);

if (
  manifestArgument === undefined ||
  privateKeyArgument === undefined ||
  publicModuleArgument === undefined
) {
  throw new Error(
    "Usage: node scripts/sign-inference-manifest.mjs <manifest> <private-key> <public-key-module> [public-key-record]",
  );
}

const manifestPath = resolve(manifestArgument);
const privateKeyPath = resolve(privateKeyArgument);
const publicModulePath = resolve(publicModuleArgument);
const publicRecordPath =
  publicRecordArgument === undefined ? null : resolve(publicRecordArgument);

const canonicalize = (value) => {
  if (Array.isArray(value)) {
    return `[${value.map(canonicalize).join(",")}]`;
  }

  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${canonicalize(value[key])}`)
      .join(",")}}`;
  }

  return JSON.stringify(value);
};

let privateKey;

if (existsSync(privateKeyPath)) {
  privateKey = createPrivateKey(readFileSync(privateKeyPath));
} else {
  const generated = generateKeyPairSync("ed25519");
  privateKey = generated.privateKey;
  mkdirSync(dirname(privateKeyPath), { recursive: true });
  writeFileSync(
    privateKeyPath,
    privateKey.export({ type: "pkcs8", format: "pem" }),
    { mode: 0o600 },
  );
  chmodSync(privateKeyPath, 0o600);
}

const publicKeyDer = createPublicKey(privateKey).export({
  type: "spki",
  format: "der",
});
const keyId = `manifest-${createHash("sha256")
  .update(publicKeyDer)
  .digest("hex")
  .slice(0, 16)}`;
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const { signature: _oldSignature, ...unsignedManifest } = manifest;
const signature = sign(
  null,
  Buffer.from(canonicalize(unsignedManifest), "utf8"),
  privateKey,
).toString("base64");

writeFileSync(
  manifestPath,
  `${JSON.stringify({
    ...unsignedManifest,
    signature: {
      algorithm: "ed25519",
      keyId,
      value: signature,
    },
  }, null, 2)}\n`,
);

if (publicRecordPath !== null) {
  mkdirSync(dirname(publicRecordPath), { recursive: true });
  writeFileSync(
    publicRecordPath,
    `${JSON.stringify({
      algorithm: "ed25519",
      keyId,
      spki: publicKeyDer.toString("base64"),
    }, null, 2)}\n`,
  );
}

mkdirSync(dirname(publicModulePath), { recursive: true });
writeFileSync(
  publicModulePath,
  `// Generated by modbots-backend/scripts/sign-inference-manifest.mjs.\n` +
    `export const inferenceManifestKeyId = ${JSON.stringify(keyId)};\n` +
    `export const inferenceManifestPublicKey = ${JSON.stringify(publicKeyDer.toString("base64"))};\n`,
);

console.log(`Signed ${manifestPath} with ${keyId}.`);
